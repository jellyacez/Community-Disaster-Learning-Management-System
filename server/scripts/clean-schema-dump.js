// Turns a production schema-only dump into server/migrations/schema.sql.
//
//   pg_dump --schema-only --no-owner --no-privileges "$DATABASE_URL" > prod-schema.sql
//   node server/scripts/clean-schema-dump.js prod-schema.sql > server/migrations/schema.sql
//
// Use a pg_dump whose major version matches production, so the file loads there.
// Removes what is specific to the machine or the dump run (\restrict, SET, search_path,
// version and timestamp lines) and every rate_limit object: @acpr/rate-limit-postgresql
// creates those on first start and crashes if they already exist without its history.
const fs = require("fs");

const input = process.argv[2];
if (!input) {
  console.error("Usage: node clean-schema-dump.js <schema-only dump.sql>");
  process.exit(1);
}

const sql = fs.readFileSync(input, "utf8").replace(/\r\n/g, "\n");
// pg_dump starts every object with "--\n-- Name: ...; Type: ...; Schema: ...; Owner: ...\n--".
const blocks = sql.split(/^(?=--\n-- Name: )/m);
const kept = blocks.filter((block) => {
  const header = block.match(/^--\n-- Name: (.*)$/m)?.[1] ?? "";
  return !/; Schema: rate_limit;/.test(header) && !/^rate_limit; Type: SCHEMA;/.test(header);
});

const cleaned = kept
  .join("")
  .split("\n")
  .filter(
    (line) =>
      !/^\\(un)?restrict\b/.test(line) &&
      !/^SET /.test(line) &&
      !/^SELECT pg_catalog\.set_config\(/.test(line) &&
      !/^-- Dumped (from|by) /.test(line) &&
      !/^-- (Started|Completed) on /.test(line),
  )
  .join("\n")
  .replace(/\n{3,}/g, "\n\n");

process.stdout.write(
  "-- Generated by server/scripts/clean-schema-dump.js from a production schema-only dump.\n" +
    "-- Do not edit by hand: schema changes go in migration.sql (see the database docs).\n" +
    cleaned.replace(/^\n+/, "\n"),
);
